'use strict';
const assert=require('node:assert/strict');
const {analisarComplementar,extrairSSCitadas,relacaoMacro,distanciaMetros}=require('./duplicidades-inteligencia');
const a={ss:'11/26-123456-01',servico:'3300 - SERVICO NO RAMAL',registro_em:'2026-11-20T12:00:00Z',chave_rua:'VILA VELHA|CENTRO|ALFREDO',numero:'100',telefone:'(27) 99999-1234',matricula:'123',hidrometro:'ABC'};
const b={ss:'11/26-654321-02',servico:'3400 - SERVICO REDE',registro_em:'2026-11-10T12:00:00Z',chave_rua:'VILA VELHA|CENTRO|ALFREDO',numero:'102',telefone:'27999991234',matricula:'321',hidrometro:'XYZ'};
assert.equal(relacaoMacro(a,b).tipo,'equivalente');
assert.equal(relacaoMacro({servico:'3995 - RECLAMACAO'},{servico:'3600 - SERVICO'}).tipo,'relacionado');
assert.equal(relacaoMacro({servico:'3600 - SERVICO'},{servico:'3600 - OUTRO'}).tipo,'igual');
assert.equal(relacaoMacro({servico:'ATENDIMENTO'},{servico:'SERVICO'}).tipo,'indisponivel');
assert.deepEqual(extrairSSCitadas({referencia_localizacao:'Referente SS 11/26 - 654321 - 02'}),['11/26-654321-02']);
const x=analisarComplementar({...a,informacao_solicitante:'EXISTE SS 11/26-654321-02'},b);
assert.equal(x.referencia_direta,true);
assert.equal(x.dias_entre_registros,10);
assert.equal(x.distancia_m,null);
assert.equal(x.apenas_informativo,true);
assert.ok(x.indicios.includes('Mesmo telefone com DDD'));
assert.ok(x.indicios.some(t=>t.includes('SS candidata citada')));
assert.ok(x.alertas.some(t=>t.includes('Matriculas divergentes')));
assert.ok(x.alertas.some(t=>t.includes('numeros diferentes')));
assert.ok(analisarComplementar(a,{...b,registro_em:'2026-11-21T12:00:00Z'}).alertas.some(t=>t.includes('depois')));
assert.ok(analisarComplementar(a,{...b,registro_em:'2025-01-01T12:00:00Z'}).alertas.some(t=>t.includes('180 dias')));
const z=analisarComplementar({latitude:-203482192950,longitude:-402921930000},{latitude:-203482192951,longitude:-402921930001});
assert.ok(z.distancia_m!==null&&z.distancia_m<=1);
assert.equal(distanciaMetros({},{}),null);
assert.ok(analisarComplementar({servico:'3995'},{servico:'3400'}).contexto.some(t=>t.includes('nao confirma')));
console.log('OK: 17 verificacoes da analise complementar; nenhuma alteracao operacional.');
